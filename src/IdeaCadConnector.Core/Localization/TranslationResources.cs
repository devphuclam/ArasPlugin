            new Dictionary<string, Dictionary<string, string>>
        {
            ["en-US"] = EnUs,
            ["vi-VN"] = ViVn,
            ["ja-JP"] = JaJp,
        };

        public static IReadOnlyCollection<string> SupportedCultures => _locales.Keys;

        public static string GetString(string culture, string key)
        {
            if (_locales.TryGetValue(culture, out var strings)
                && strings.TryGetValue(key, out var value))
            {
                return value;
            }

            if (culture != "en-US"
                && _locales.TryGetValue("en-US", out var enStrings)
                && enStrings.TryGetValue(key, out var enValue))
            {
                return enValue;
            }

            return $"[?{key}?]";
        }
